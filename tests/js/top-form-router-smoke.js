const assert = require('assert');

class FakeClassList {
    constructor() {
        this.values = new Set();
    }

    toggle(name, enabled) {
        if (enabled) {
            this.values.add(name);
            return;
        }

        this.values.delete(name);
    }

    has(name) {
        return this.values.has(name);
    }
}

class FakeElement {
    constructor(id = '') {
        this.id = id;
        this.value = '';
        this.checked = false;
        this.hidden = false;
        this.scrollTop = 0;
        this.dataset = {};
        this.listeners = {};
        this.attributes = {};
        this.classList = new FakeClassList();
    }

    addEventListener(type, listener) {
        this.listeners[type] = listener;
    }

    setAttribute(name, value) {
        this.attributes[name] = value;
    }
}

const elements = new Map();
for (const id of [
    'content',
    'sessions-view',
    'meeting-detail-view',
    'protocol-view',
    'show-top-form',
    'hide-top-form',
    'top-form-panel',
    'top-type',
    'top-subject',
    'top-person',
    'top-legal',
    'top-resolution',
    'top-invitation-note',
    'top-attachments',
    'top-resolution-count',
    'top-requires-resolution',
    'top-protocol-content',
    'top-resolution-kind',
    'top-agenda-kind',
    'top-person-field',
    'top-legal-field',
    'top-resolution-options'
]) {
    elements.set(id, new FakeElement(id));
}

global.window = {};
global.document = {
    documentElement: { scrollTop: 9 },
    body: { scrollTop: 8 }
};

require('../../js/modules/view-router.js');
require('../../js/components/top-form.js');

const byId = (id) => elements.get(id) || null;

elements.get('content').scrollTop = 7;
const router = window.BRTop.viewRouter.createController({
    byId,
    viewIds: ['sessions-view', 'meeting-detail-view', 'protocol-view']
});
router.show('meeting-detail-view');

assert.strictEqual(elements.get('meeting-detail-view').hidden, false);
assert.strictEqual(elements.get('meeting-detail-view').classList.has('is-active'), true);
assert.strictEqual(elements.get('meeting-detail-view').attributes['aria-hidden'], 'false');
assert.strictEqual(elements.get('sessions-view').hidden, true);
assert.strictEqual(elements.get('sessions-view').attributes['aria-hidden'], 'true');
assert.strictEqual(elements.get('content').scrollTop, 0);
assert.strictEqual(document.documentElement.scrollTop, 0);
assert.strictEqual(document.body.scrollTop, 0);

elements.get('top-type').value = 'personnel_99';
elements.get('top-subject').value = 'Einstellung Anna';
elements.get('top-person').value = 'Anna';
elements.get('top-invitation-note').value = 'Unterlagen vorher lesen';
elements.get('top-attachments').value = 'anlage.pdf';
elements.get('top-resolution-count').value = '2';
elements.get('top-requires-resolution').checked = true;
elements.get('top-resolution').dataset.autoGenerated = '1';

const form = window.BRTop.topForm.createController(byId);
form.init();

assert.strictEqual(elements.get('top-legal').value, '\u00a7 99 BetrVG');
assert.strictEqual(elements.get('top-resolution-kind').value, 'consent_refusal');
assert.strictEqual(elements.get('top-agenda-kind').value, 'discussion');
assert.strictEqual(elements.get('top-person-field').hidden, false);
assert.strictEqual(elements.get('top-legal-field').hidden, false);
assert.strictEqual(elements.get('top-resolution-options').hidden, false);
assert(elements.get('top-resolution').value.includes('Wer verweigert die Zustimmung'));
assert(elements.get('top-resolution').value.includes('Beschlussfrage 2'));

assert.deepStrictEqual(form.payload(), {
    type: 'personnel_99',
    parentId: 0,
    agendaItemKind: 'discussion',
    subject: 'Einstellung Anna',
    personName: 'Anna',
    legalBasis: '\u00a7 99 BetrVG',
    resolutionText: elements.get('top-resolution').value,
    requiresResolution: true,
    resolutionCount: 2,
    invitationNote: 'Unterlagen vorher lesen',
    attachmentPaths: 'anlage.pdf',
    protocolContent: ''
});

elements.get('top-resolution').value = 'Eigene Frage';
elements.get('top-resolution').listeners.input();
elements.get('top-subject').value = 'Neuer Betreff';
elements.get('top-subject').listeners.input();
assert.strictEqual(elements.get('top-resolution').value, 'Eigene Frage');

elements.get('top-resolution-count').value = '0';
elements.get('top-resolution-count').listeners.input();
assert.strictEqual(elements.get('top-resolution-count').value, '1');

form.show();
assert.strictEqual(elements.get('top-form-panel').hidden, false);
assert.strictEqual(elements.get('show-top-form').attributes['aria-expanded'], 'true');
form.hide();
assert.strictEqual(elements.get('top-form-panel').hidden, true);
assert.strictEqual(elements.get('show-top-form').attributes['aria-expanded'], 'false');

form.clear();
assert.strictEqual(elements.get('top-subject').value, '');
assert.strictEqual(elements.get('top-requires-resolution').checked, false);
assert.strictEqual(elements.get('top-resolution-count').value, '1');
assert.strictEqual(elements.get('top-resolution').dataset.autoGenerated, '1');
assert.strictEqual(elements.get('top-resolution-options').hidden, true);

elements.get('top-type').value = 'consultation_report';
elements.get('top-type').listeners.change();
assert.strictEqual(elements.get('top-agenda-kind').value, 'report');

console.log('BRTop top form and router smoke test passed.');
